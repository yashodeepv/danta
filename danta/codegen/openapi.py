"""openapi.py - The system's contracts, from IR2: OpenAPI for HTTP, AsyncAPI for topics.

    openapi(system)    OpenAPI 3.0 document: one operation per HTTP-triggered flow
    asyncapi(system)   AsyncAPI 2.6 document: one channel per topic, with who
                       publishes to it and who subscribes

Schemas come straight from the IR2 types, so the documents can't drift from
the code: request bodies are trigger payloads, success bodies are the fields
the flow's `ok` ends respond with, error bodies add `error` to the fields its
`error` ends respond with. Every language's project serves the same document.
"""

from danta.check.dataflow import check_dataflow
from danta.check.diagnostics import Report
from danta.check.typing import TypeErr, type_of
from danta.gen.order import canonical_order
from danta.ir2 import graph as g
from danta.ir2.types import BOOL, INT, STR, UNKNOWN, ListT, RecordT


def schema(t):
    if t == INT:
        return {'type': 'integer', 'format': 'int32'}
    if t == STR:
        return {'type': 'string'}
    if t == BOOL:
        return {'type': 'boolean'}
    if isinstance(t, ListT):
        return {'type': 'array', 'items': schema(t.elem)}
    if isinstance(t, RecordT):
        return {'type': 'object', 'properties': {n: schema(ft) for n, ft in t.fields},
                'required': [n for n, _ in t.fields], 'additionalProperties': False}
    return {}


def _end_fields(flow, status):
    """{field: schema} over every end with this status that responds."""
    scopes = check_dataflow(flow, canonical_order(flow), Report())
    out = {}
    for s in flow.steps:
        if isinstance(s, g.End) and s.status == status and s.response:
            for k, e in s.response.items():
                try:
                    t = type_of(e, scopes[s.id])
                except TypeErr:
                    t = UNKNOWN
                out.setdefault(k, schema(t))
    return out


def _title(flow):
    return (flow.intent or flow.name.replace('_', ' ')).split('. ')[0][:120]


def openapi(system):
    paths = {}
    for f in system.flows:
        t = f.trigger()
        if t.source != 'http':
            continue
        op = {
            'operationId': f.name,
            'summary': _title(f),
            'description': f.intent or '',
            'requestBody': {'required': True, 'content': {'application/json': {'schema': schema(t.payload)}}},
            'responses': {'400': {'description': 'Missing or malformed field',
                                  'content': {'application/json': {'schema': {
                                      'type': 'object', 'properties': {'error': {'type': 'string'}}}}}}},
        }
        if f.mode == 'async':
            op['responses']['202'] = {'description': 'Accepted: the flow runs in the background',
                                      'content': {'application/json': {'schema': {
                                          'type': 'object', 'properties': {'accepted': {'type': 'boolean'}}}}}}
        else:
            ok = _end_fields(f, 'ok')
            op['responses']['200'] = {'description': 'The flow finished',
                                      'content': {'application/json': {'schema': {
                                          'type': 'object', 'properties': ok}}}}
            err = {'error': {'type': 'string'}, **_end_fields(f, 'error')}
            op['responses']['422'] = {'description': 'The flow stopped with an error',
                                      'content': {'application/json': {'schema': {
                                          'type': 'object', 'properties': err}}}}
        paths.setdefault(t.config['path'], {})[t.config['method'].lower()] = op
    from danta.codegen.project.common import data_entities
    for entity, fields in data_entities(system).items():
        paths[f'/data/{entity}'] = {'get': {
            'operationId': f'list_{entity}',
            'summary': f'{entity} records, for the list screens',
            'tags': ['data'],
            'parameters': [{'name': n, 'in': 'query', 'required': False, 'schema': schema(ft)}
                           for n, ft in system.entities[entity].fields if n in fields],
            'responses': {'200': {'description': f'The {entity} records whose fields equal the given values',
                                  'content': {'application/json': {'schema': {
                                      'type': 'array', 'items': {'$ref': f'#/components/schemas/{entity}'}}}}},
                          '400': {'description': 'An unknown field, or a malformed value'}}}}
    return {
        'openapi': '3.0.3',
        'info': {'title': system.name, 'version': '0.1.0',
                 'description': (system.description or '') + '\n\nGenerated by Danta from a Danta Spec.'},
        'paths': paths,
        'components': {'schemas': {e: schema(rec) for e, rec in system.entities.items()}},
    }


def asyncapi(system):
    """Channels: topics (published or subscribed), and the scheduled and event triggers."""
    channels = {}

    def channel(name):
        return channels.setdefault(name, {'description': '', 'x-published-by': [], 'x-subscribed-by': []})

    for f in system.flows:
        t = f.trigger()
        if t.source == 'topic':
            c = channel(t.config['name'])
            c['x-subscribed-by'].append(f.name)
            c['subscribe'] = {'operationId': f.name, 'summary': _title(f),
                              'message': {'payload': schema(t.payload)}}
        scopes = None
        for s in f.steps:
            if isinstance(s, g.Publish):
                c = channel(s.topic)
                c['x-published-by'].append(f.name)
                if scopes is None:
                    scopes = check_dataflow(f, canonical_order(f), Report())
                try:
                    if s.each is not None:
                        payload = schema(type_of(s.each, scopes[s.id]).elem)
                    else:
                        payload = schema(RecordT(tuple((k, type_of(e, scopes[s.id])) for k, e in s.message.items())))
                except (TypeErr, AttributeError):
                    payload = {}
                c.setdefault('publish', {'operationId': f'{f.name}_{s.id}', 'summary': s.title or f'published by {f.name}',
                                         'message': {'payload': payload}})
    for name, c in channels.items():
        who = []
        if c['x-published-by']:
            who.append('published by ' + ', '.join(c['x-published-by']))
        if c['x-subscribed-by']:
            who.append('consumed by ' + ', '.join(c['x-subscribed-by']))
        c['description'] = '; '.join(who)
    schedules = [{'flow': f.name, 'cron': f.trigger().config['cron']} for f in system.flows
                 if f.trigger().source == 'schedule']
    events = [{'flow': f.name, 'event': f.trigger().config['name']} for f in system.flows
              if f.trigger().source == 'event']
    return {
        'asyncapi': '2.6.0',
        'info': {'title': f'{system.name} topics', 'version': '0.1.0',
                 'description': 'Messages the flows publish and consume. Generated by Danta.'},
        'channels': channels,
        'x-schedules': schedules,
        'x-events': events,
    }
